"""Replay all migrations in isolated MySQL, then generate/check JUnit fixture subsets."""
import argparse
import importlib.util
import os
import re
from pathlib import Path
import shutil
import tempfile
import subprocess
import time
from db_migrate import Database, MIGRATIONS, reference

ROOT = Path(__file__).resolve().parents[1]
MODULE_TABLES = {
    'user': ('t_user', 't_address'),
    'admin': ('t_admin_account',),
    'product': ('t_category', 't_product', 't_product_attr', 't_product_sku', 't_admin_account'),
    'order': ('t_user', 't_address', 't_category', 't_product', 't_product_attr',
              't_orders', 't_order_item', 't_order_idempotency','t_product_sku','t_catalog_migration','t_admin_account'),
}


def sync(check=False, mysql_home=None):
    reference()  # V1 remains immutable.
    spec = importlib.util.spec_from_file_location('fixture_verification', ROOT / 'scripts/verify-system.py')
    system = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(system)
    mysql = Path(mysql_home or os.environ.get('XIAOKE_MYSQL_HOME', 'D:/Develop/mysql-8.0.34-winx64')).resolve()
    verifier = system.Verification(mysql, 4, 1)
    try:
        verifier.start_database()
        env = os.environ.copy()
        env.update({'XIAOKE_MIGRATION_HOST': '127.0.0.1', 'XIAOKE_MIGRATION_PORT': str(verifier.port),
                    'XIAOKE_MIGRATION_DATABASE': verifier.schemas['order'],
                    'XIAOKE_MIGRATION_USER': 'root', 'XIAOKE_MIGRATION_PASSWORD': ''})
        db = Database(str(mysql), env)
        versions = list(MIGRATIONS.glob('V*.sql'))
        def version(path):
            match = re.fullmatch(r'V(\d+)__.+\.sql', path.name)
            if not match:
                raise RuntimeError('Unsupported migration filename: ' + path.name)
            return int(match[1])
        versions.sort(key=version)
        if len({version(path) for path in versions}) != len(versions):
            raise RuntimeError('Duplicate migration versions')
        for path in versions:
            db.query(path.read_text(encoding='utf-8-sig'))
        tables = db.structure()['ddl']
        if set(tables) != set(MODULE_TABLES['order']):
            raise RuntimeError('Update MODULE_TABLES to match all current business tables')
        for module, names in MODULE_TABLES.items():
            path = ROOT / f'xiaoke-{module}/src/test/resources/{module}-schema.sql'
            body = '-- Generated by replaying all sql/migration/V*.sql in isolated MySQL. Tests only.\n'
            body += '-- Update with: python scripts/sync-test-schemas.py\n\n'
            body += '\n\n'.join(tables[name] + ';' for name in names) + '\n'
            if module == 'user':
                body = body.replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ')
            if check:
                if path.read_text(encoding='utf-8') != body:
                    raise RuntimeError(f'Test schema drift: {path.relative_to(ROOT)}')
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(body, encoding='utf-8', newline='\n')
            print(('Checked ' if check else 'Generated ') + str(path.relative_to(ROOT)), flush=True)
        return tables
    finally:
        if verifier.server is not None and verifier.server.poll() is None:
            subprocess.run(verifier.client + ['--execute', 'SHUTDOWN'], capture_output=True,
                           timeout=15, creationflags=system.FLAGS)
        system.stop(verifier.server)
        if verifier.data.parent != Path(tempfile.gettempdir()).resolve() or not verifier.data.name.startswith('xiaoke-final-mysql-'):
            raise RuntimeError('Refusing unexpected temporary directory')
        if verifier.server is not None and verifier.server.poll() is None:
            raise RuntimeError('Temporary MySQL is still running')
        for attempt in range(15):
            try:
                shutil.rmtree(verifier.data)
                break
            except OSError:
                if attempt==14:
                    raise
                time.sleep(0.3)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--mysql-home')
    args = parser.parse_args()
    if Path.cwd().resolve() != ROOT:
        parser.error('Run from the repository root')
    sync(args.check, args.mysql_home)
